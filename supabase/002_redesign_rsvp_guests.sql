-- Redesign RSVP: replace flat adults/children counts with named, per-guest records.
-- Supersedes 001_create_rsvp_schema.sql's rsvp_responses table (no production data to migrate).

drop table if exists public.rsvp_responses;

create table if not exists public.rsvp_parties (
    id integer generated by default as identity primary key,
    notes text null check (notes is null or char_length(notes) <= 1000),
    created_at_utc timestamptz not null default now()
);

create index if not exists ix_rsvp_parties_created_at_utc
    on public.rsvp_parties (created_at_utc desc);

create table if not exists public.rsvp_guests (
    id integer generated by default as identity primary key,
    party_id integer not null references public.rsvp_parties(id) on delete cascade,
    first_name text not null check (char_length(btrim(first_name)) between 1 and 100),
    last_name text not null check (char_length(btrim(last_name)) between 1 and 100),
    is_child boolean not null default false,
    age smallint null check (age is null or age between 0 and 17),
    allergies text null check (allergies is null or char_length(allergies) <= 500),
    is_primary_contact boolean not null default false,
    guest_order smallint not null default 0,
    constraint rsvp_guests_age_matches_is_child check (
        (is_child and age is not null) or (not is_child and age is null)
    )
);

create index if not exists ix_rsvp_guests_party_id
    on public.rsvp_guests (party_id);

create unique index if not exists ix_rsvp_guests_one_primary_per_party
    on public.rsvp_guests (party_id)
    where is_primary_contact;

create or replace function public.enforce_rsvp_party_guest_limit()
returns trigger
language plpgsql
as $$
begin
    if (
        select count(*) from public.rsvp_guests where party_id = new.party_id
    ) > 12 then
        raise exception 'A party cannot have more than 12 guests';
    end if;
    return new;
end;
$$;

drop trigger if exists trg_enforce_rsvp_party_guest_limit on public.rsvp_guests;
create trigger trg_enforce_rsvp_party_guest_limit
after insert or update on public.rsvp_guests
for each row
execute function public.enforce_rsvp_party_guest_limit();

alter table public.rsvp_parties enable row level security;
alter table public.rsvp_guests enable row level security;

