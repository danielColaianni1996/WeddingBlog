-- Atomic RPC used by the public RSVP form (anon) and by the admin "create" flow.
-- p_guests shape: [{ "first_name": text, "last_name": text, "is_child": bool,
--                     "age": int|null, "allergies": text|null, "is_primary_contact": bool }, ...]
create or replace function public.submit_rsvp(p_notes text, p_guests jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_party_id integer;
    v_guest_count integer;
    v_primary_count integer;
begin
    select count(*) into v_guest_count from jsonb_array_elements(p_guests);

    if v_guest_count < 1 or v_guest_count > 12 then
        raise exception 'A party must have between 1 and 12 guests';
    end if;

    select count(*) into v_primary_count
    from jsonb_array_elements(p_guests) as g
    where (g->>'is_primary_contact')::boolean;

    if v_primary_count <> 1 then
        raise exception 'Exactly one guest must be the primary contact';
    end if;

    insert into public.rsvp_parties (notes)
    values (nullif(btrim(coalesce(p_notes, '')), ''))
    returning id into v_party_id;

    insert into public.rsvp_guests (
        party_id, first_name, last_name, is_child, age, allergies,
        is_primary_contact, guest_order
    )
    select
        v_party_id,
        g->>'first_name',
        g->>'last_name',
        coalesce((g->>'is_child')::boolean, false),
        nullif(g->>'age', '')::smallint,
        nullif(btrim(coalesce(g->>'allergies', '')), ''),
        coalesce((g->>'is_primary_contact')::boolean, false),
        (row_number() over () - 1)::smallint
    from jsonb_array_elements(p_guests) as g;

    return v_party_id;
end;
$$;

grant execute on function public.submit_rsvp(text, jsonb) to anon, authenticated;

-- Atomic RPC used by the admin panel to edit an existing party: replaces its
-- entire guest list (delete + reinsert) so partial/inconsistent updates can't happen.
create or replace function public.admin_update_rsvp_party(
    p_party_id integer, p_notes text, p_guests jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    v_guest_count integer;
    v_primary_count integer;
begin
    if not public.is_admin() then
        raise exception 'Only admins can update RSVP parties';
    end if;

    select count(*) into v_guest_count from jsonb_array_elements(p_guests);

    if v_guest_count < 1 or v_guest_count > 12 then
        raise exception 'A party must have between 1 and 12 guests';
    end if;

    select count(*) into v_primary_count
    from jsonb_array_elements(p_guests) as g
    where (g->>'is_primary_contact')::boolean;

    if v_primary_count <> 1 then
        raise exception 'Exactly one guest must be the primary contact';
    end if;

    update public.rsvp_parties
    set notes = nullif(btrim(coalesce(p_notes, '')), '')
    where id = p_party_id;

    delete from public.rsvp_guests where party_id = p_party_id;

    insert into public.rsvp_guests (
        party_id, first_name, last_name, is_child, age, allergies,
        is_primary_contact, guest_order
    )
    select
        p_party_id,
        g->>'first_name',
        g->>'last_name',
        coalesce((g->>'is_child')::boolean, false),
        nullif(g->>'age', '')::smallint,
        nullif(btrim(coalesce(g->>'allergies', '')), ''),
        coalesce((g->>'is_primary_contact')::boolean, false),
        (row_number() over () - 1)::smallint
    from jsonb_array_elements(p_guests) as g;
end;
$$;

grant execute on function public.admin_update_rsvp_party(integer, text, jsonb) to authenticated;
